from emachine.machines.tfm.cad import sheet as onshape

MESHER = ["-m", "emachine", "mesh"]

#: The Fig. 17 stator at the size of the current problem (80 mm outrunner).
STATOR = {"core_type": "tr", "air_gap_radius": 35.0, "pole_pairs": 16, "inner_stator": True, "tooth_span": 0.6,
          "leg_width": 3.0, "slot_width": 8.0, "slot_height": 12.0, "yoke_height": 4.0, "ring_tooth_height": 5.0,
          "coil_height": 5.0, "coil_clearance": 0.5, "pole_shift_deg": 0.0}
ROTORS = {
    "outrunner": {"configuration": "outrunner", "inner_diameter": 71.0, "outer_diameter": 80.0},
    "inrunner": {"configuration": "inrunner", "outer_diameter": 69.0, "shaft_diameter": 40.0},
}


def params(style, **stator_changes):
    stator = dict(STATOR, inner_stator=style == "outrunner", **stator_changes)
    rotor = dict(ROTORS[style], type="halbach", stack_length=14.0, poles=32, magnet_thickness=2.5,
                 segments_per_pole=2, magnet_rows=2, row_gap=8.0, alternate_rows=True)
    return {"stator": stator, "rotor": rotor}


def strip_area(rho, a):
    """Area under sqrt(rho^2 - y^2) for |y| <= a: a disc of radius rho cut by a strip of half width a."""
    return a * math.sqrt(rho * rho - a * a) + rho * rho * math.asin(a / rho)


def closed_form(sp):
    """Core and coil volume of the toothed ring, in mm^3."""
    R, p, sign = sp["air_gap_radius"], sp["pole_pairs"], -1 if sp["inner_stator"] else 1
    a = sp["tooth_span"] * R * math.pi / p / 2
    leg, slot_w, slot_h, h_t = sp["leg_width"], sp["slot_width"], sp["slot_height"], sp["ring_tooth_height"]
    top = slot_h + sp["yoke_height"]

    def ring(z0, z1, width):
        return math.pi * abs((R + sign * z1) ** 2 - (R + sign * z0) ** 2) * width

    # A tooth outside the ring is the part of its strip between the air-gap cylinder and the cylinder at h_t.
    teeth = p * 2 * leg * abs(strip_area(R + sign * h_t, a) - strip_area(R, a))
    core = ring(h_t, slot_h, 2 * leg) + ring(slot_h, top, slot_w + 2 * leg) + teeth
    cl = sp["coil_clearance"]
    coil = ring(slot_h - cl - sp["coil_height"], slot_h - cl, slot_w - 2 * cl)
    return core, coil


def stator_only(tmp, stator):
    path = os.path.join(tmp, "stator.json")
    with open(path, "w") as f:
        json.dump({"stator": stator}, f)
    return subprocess.run([sys.executable, *MESHER, "--params", path, "--stator-only", "--out",
                           os.path.join(tmp, "stator.brep")], capture_output=True, text=True, cwd=ROOT)


class FeatureScriptTest(unittest.TestCase):
    def read(self, name):
        with open(os.path.join(FEATURESCRIPT, name)) as f:
            return f.read()

    def test_t24_4_featurescript(self):
        stator = self.read("tfm_stator.fs")
        self.assertRegex(stator, r'annotation \{ "Name" : "Toothed ring \(Fig\. 17\)" \}\s*TR_CORE,')
        self.assertIn('annotation { "Name" : "Ring tooth height" }', stator)
        self.assertIn('isLength(definition.ringToothHeight, ', stator)
        self.assertIn('"ringToothHeight" : 8 * millimeter', stator)
        self.assertIn("The ring tooth height must be smaller than the slot height.", stator)
        # Both styles: the rings follow the sign of the layout, so inner and outer stator are built.
        self.assertIn("layout.radius + layout.sign * hWall", stator)
        # The machine file carries the same stator code, as a function generated by emachine ui32 (T25).
        from emachine.machines.tfm.cad import ui32_build as tfm_ui32_build
        self.assertEqual(tfm_ui32_build.build(), self.read("tfm_ui32_design.fs"))
        self.assertIn("layout.radius + layout.sign * hWall", self.read("tfm_ui32_design.fs"))

    def test_sheet_fields_exist_in_the_dialog(self):
        labels = set(re.findall(r'annotation\s*\{\s*"Name"\s*:\s*"([^"]+)"', self.read("tfm_stator.fs")))
        rows = {r["field"]: r for r in onshape.stator_rows(STATOR)}
        self.assertEqual(rows["Core structure"]["text"], "Toothed ring (Fig. 17)")
        self.assertEqual(rows["Ring tooth height"]["value"], 5.0)
        for field in rows:
            self.assertIn(field, labels)
        self.assertIn(rows["Core structure"]["text"], labels)


@slow
class MesherTest(unittest.TestCase):
    def test_t24_1_volumes(self):
        for inner in (True, False):
            for shift in (0.0, 3.0):
                with self.subTest(inner_stator=inner, pole_shift_deg=shift), tempfile.TemporaryDirectory() as tmp:
                    sp = dict(STATOR, inner_stator=inner, pole_shift_deg=shift)
                    result = stator_only(tmp, sp)
                    self.assertEqual(result.returncode, 0, result.stderr[-800:])
                    volumes = {m.group(1): (int(m.group(2)), float(m.group(3))) for m in
                               re.finditer(r"volume\s+(\S+)\s+(\d+) solids\s+([\d.]+) mm\^3", result.stdout)}
                    core, coil = closed_form(sp)
                    self.assertEqual(volumes["tfm_core"][0], 1)                 # one piece of iron
                    self.assertAlmostEqual(volumes["tfm_core"][1] / core, 1.0, delta=0.001)
                    self.assertAlmostEqual(volumes["tfm_coil"][1] / coil, 1.0, delta=0.001)

    def test_t24_5_tooth_height_outside_range(self):
        for height in (0.0, STATOR["slot_height"]):
            with self.subTest(ring_tooth_height=height), tempfile.TemporaryDirectory() as tmp:
                result = stator_only(tmp, dict(STATOR, ring_tooth_height=height))
                self.assertNotEqual(result.returncode, 0)
                self.assertIn("ring tooth height must lie between 0 and the slot height", result.stderr)

    def test_t24_2_sector_mesh(self):
        for style in ("outrunner", "inrunner"):
            with self.subTest(style=style), tempfile.TemporaryDirectory() as tmp:
                path = os.path.join(tmp, "machine.json")
                with open(path, "w") as f:
                    json.dump(params(style), f)
                mesh = os.path.join(tmp, "sector.msh")
                result = subprocess.run([sys.executable, *MESHER, "--params", path, "--out", mesh],
                                        capture_output=True, text=True, cwd=ROOT)
                self.assertEqual(result.returncode, 0, result.stdout[-800:] + result.stderr[-800:])
                check = subprocess.run([sys.executable, "-m", "emachine", "check-mesh", mesh],
                                       capture_output=True, text=True, cwd=ROOT)
                self.assertEqual(check.returncode, 0, check.stderr[-800:])
                self.assertIn("node ids shared between the two sides: 0 ", check.stdout)
                sliding = re.search(r"coincident positions: (\d+) of (\d+)", check.stdout)
                self.assertEqual(sliding.group(1), sliding.group(2))
                planes = re.findall(r"A (\d+) nodes, B (\d+) nodes, matched after rotation (\d+)", check.stdout)
                self.assertEqual(len(planes), 2)
                for a, b, hits in planes:
                    self.assertTrue(a == b == hits, planes)


@slow
class FieldTest(unittest.TestCase):
    def test_t24_3_no_load_flux_changes_sign(self):
        from emachine.pipeline import sweep
        from emachine.solvers.elmer.sector3d import ANALYSIS_DEFAULTS
        analysis = dict(ANALYSIS_DEFAULTS, coil_turns=1)
        machine = params("outrunner")
        pitch = 180.0 / STATOR["pole_pairs"]
        with tempfile.TemporaryDirectory() as tmp:
            fluxes = [sweep.solve_position(machine, analysis, angle, os.path.join(tmp, f"p{k}"),
                                                  current=0.0)["flux_linkage_Wb"]
                      for k, angle in enumerate((0.0, pitch))]
        self.assertLess(fluxes[0] * fluxes[1], 0.0, fluxes)
        self.assertAlmostEqual(abs(fluxes[1] / fluxes[0]), 1.0, delta=0.2)


